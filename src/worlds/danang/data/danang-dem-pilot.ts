const BASE64_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

/** Decode base64 to a little-endian Float32Array without Node-only APIs. */
export function decodeBase64ToFloat32(base64: string): Float32Array {
  const cleaned = base64.replace(/[^A-Za-z0-9+/=]/g, '');
  const lookup = new Map<string, number>();
  for (let index = 0; index < BASE64_ALPHABET.length; index++) lookup.set(BASE64_ALPHABET[index]!, index);
  const bytes: number[] = [];
  for (let index = 0; index < cleaned.length; index += 4) {
    const chunk = cleaned.slice(index, index + 4);
    if (chunk.length < 4) throw new Error('Invalid base64 length in DEM pilot asset');
    let padding = 0;
    if (chunk.endsWith('==')) padding = 2;
    else if (chunk.endsWith('=')) padding = 1;
    const values = [...chunk.slice(0, 4 - padding)].map((char) => lookup.get(char));
    if (values.some((value) => value === undefined)) throw new Error('Invalid base64 character in DEM pilot asset');
    const triple = ((values[0] ?? 0) << 18) | ((values[1] ?? 0) << 12) | ((values[2] ?? 0) << 6) | (values[3] ?? 0);
    bytes.push((triple >> 16) & 0xff, (triple >> 8) & 0xff, triple & 0xff);
  }
  let padding = 0;
  if (cleaned.endsWith('==')) padding = 2;
  else if (cleaned.endsWith('=')) padding = 1;
  const byteLength = bytes.length - padding;
  const buffer = new Uint8Array(bytes.slice(0, byteLength)).buffer;
  if (buffer.byteLength % 4 !== 0) throw new Error('DEM pilot asset byte length is not a multiple of 4');
  return new Float32Array(buffer);
}

